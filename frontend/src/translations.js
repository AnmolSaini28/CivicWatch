export function translateGender(gender, language) {
  if (language !== "hi") return gender || "";
  const g = String(gender || "").toLowerCase().trim();
  if (g === "male") return "पुरुष";
  if (g === "female") return "महिला";
  if (g === "other") return "अन्य";
  if (g.includes("prefer")) return "बताना नहीं चाहते";
  return gender;
}
