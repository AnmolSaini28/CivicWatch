export function translateStatus(status, language) {
  if (language !== "hi") return status || "Pending";
  const s = String(status || "").toLowerCase().trim();
  if (s === "pending") return "लंबित";
  if (s === "in progress" || s === "inprogress") return "प्रगति पर";
  if (s === "resolved") return "हल हो गया";
  return status;
}

